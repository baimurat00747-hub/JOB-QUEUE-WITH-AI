from contextlib import closing

import psycopg
from psycopg.rows import dict_row

from .store import Store, schema

SCHEMA = schema("BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "BIGINT", "BIGINT")


def database_time(conn):
    return conn.execute(
        "SELECT floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint AS now_ms"
    ).fetchone()["now_ms"]


class PostgresStore(Store):
    def __init__(self, url, clock=database_time):
        self.url = url
        self.clock = clock

    def connect(self):
        return psycopg.connect(
            self.url,
            autocommit=True,
            row_factory=dict_row,
            connect_timeout=5,
            options="-c lock_timeout=2000 -c statement_timeout=5000",
        )

    def initialize(self):
        with closing(self.connect()) as conn, conn.transaction():
            conn.execute("SELECT pg_advisory_xact_lock(60111814)")
            conn.execute(SCHEMA)

    @staticmethod
    def query(conn, sql, params=()):
        return conn.execute(sql.replace("?", "%s"), params)

    @staticmethod
    def write(conn):
        return conn.transaction()

    def claim(self, conn, lease_ms):
        with self.write(conn):
            job = conn.execute(
                """SELECT id FROM jobs
                   WHERE state = 'queued' OR (state = 'running' AND lease_until_ms <= %s)
                   ORDER BY id LIMIT 1 FOR UPDATE SKIP LOCKED""",
                (self.clock(conn),),
            ).fetchone()
            if job is None:
                return None
            return self.start_attempt(conn, job["id"], self.clock(conn), lease_ms)

    def owner_time(self, conn, job_id):
        # Sample the clock after waiting for a competing update to this row.
        conn.execute("SELECT id FROM jobs WHERE id = %s FOR UPDATE", (job_id,)).fetchone()
        return self.clock(conn)
